let currentLanguage = 'en';
const form = document.getElementById('contact-form');
const submitButton = document.getElementById('submit-button');
const formStatus = document.getElementById('form-status');

/**
 * Gets a nested translation string for the active language.
 * @param {string} key - Translation key, optionally using dot notation.
 * @returns {string} The translated string or an empty string when not found.
 */
function getTranslation(key) {
  return key.split('.').reduce((value, part) => value?.[part], translations[currentLanguage]) ?? '';
}

/**
 * Applies the active language to text and placeholder attributes in the document.
 * @returns {void}
 */
function applyLanguage() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = getTranslation(element.dataset.i18n);
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = getTranslation(element.dataset.i18nPlaceholder);
    if (value) element.setAttribute('placeholder', value);
  });

  document.querySelectorAll('.language-button').forEach((button) => {
    const active = button.dataset.language === currentLanguage;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  updateDocumentTitle();
  clearValidationMessages();
}

/**
 * Updates the document title after a language change.
 * @returns {void}
 */
function updateDocumentTitle() {
  document.title = currentLanguage === 'de'
    ? 'Leon Weigang | Frontend Developer'
    : 'Leon Weigang | Frontend Developer';
}

/**
 * Changes the active website language and closes the mobile navigation.
 * @param {'de'|'en'} language - Language code to activate.
 * @returns {void}
 */
function setLanguage(language) {
  if (!translations[language]) return;
  currentLanguage = language;
  applyLanguage();
  closeMobileMenu();
}

/**
 * Opens the mobile navigation and updates its accessibility state.
 * @returns {void}
 */
function openMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const toggle = document.querySelector('.menu-toggle');
  menu.classList.add('is-open');
  menu.setAttribute('aria-hidden', 'false');
  toggle.setAttribute('aria-expanded', 'true');
  toggle.setAttribute('aria-label', currentLanguage === 'de' ? 'Menü schließen' : 'Close menu');
  document.body.classList.add('menu-open');
}

/**
 * Closes the mobile navigation and restores the page scroll state.
 * @returns {void}
 */
function closeMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const toggle = document.querySelector('.menu-toggle');
  if (!menu || !toggle) return;
  menu.classList.remove('is-open');
  menu.setAttribute('aria-hidden', 'true');
  toggle.setAttribute('aria-expanded', 'false');
  toggle.setAttribute('aria-label', currentLanguage === 'de' ? 'Menü öffnen' : 'Open menu');
  document.body.classList.remove('menu-open');
}

/**
 * Toggles the mobile navigation open or closed.
 * @returns {void}
 */
function toggleMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  if (menu.classList.contains('is-open')) {
    closeMobileMenu();
  } else {
    openMobileMenu();
  }
}

/**
 * Validates one form field after it has lost focus.
 * @param {HTMLInputElement|HTMLTextAreaElement} field - Field to validate.
 * @returns {boolean} True when the field is valid.
 */
function validateField(field) {
  const errorElement = document.getElementById(`${field.id}-error`);
  if (!errorElement) return true;

  let message = '';
  if (field.id === 'name' && field.value.trim().length < 2) message = getTranslation('errors.name');
  if (field.id === 'email' && !field.validity.valid) message = getTranslation('errors.email');
  if (field.id === 'message' && field.value.trim().length < 10) message = getTranslation('errors.message');

  field.setAttribute('aria-invalid', String(Boolean(message)));
  errorElement.textContent = message;
  return !message;
}

/**
 * Validates the privacy checkbox separately from text fields.
 * @returns {boolean} True when the privacy checkbox is accepted.
 */
function validatePrivacy() {
  const checkbox = document.getElementById('privacy');
  const errorElement = document.getElementById('privacy-error');
  const valid = checkbox.checked;
  checkbox.setAttribute('aria-invalid', String(!valid));
  errorElement.textContent = valid ? '' : getTranslation('errors.privacy');
  return valid;
}

/**
 * Validates all required fields and updates the submit button state.
 * @returns {boolean} True when the complete form is valid.
 */
function validateForm() {
  const fieldsValid = ['name', 'email', 'message']
    .map((id) => validateField(document.getElementById(id)))
    .every(Boolean);
  const privacyValid = validatePrivacy();
  const valid = fieldsValid && privacyValid;
  updateSubmitButton();
  return valid;
}

/**
 * Removes all currently displayed validation messages.
 * @returns {void}
 */
function updateSubmitButton() {
  if (!form || !submitButton) return;
  const privacy = document.getElementById('privacy');
  submitButton.disabled = !(form.checkValidity() && Boolean(privacy?.checked));
}

/**
 * Removes all currently displayed validation messages without forcing validation.
 * @returns {void}
 */
function clearValidationMessages() {
  document.querySelectorAll('.field-error').forEach((element) => { element.textContent = ''; });
  document.querySelectorAll('[aria-invalid="true"]').forEach((element) => element.setAttribute('aria-invalid', 'false'));
  if (formStatus) {
    formStatus.textContent = '';
    formStatus.className = 'form-status';
  }
  updateSubmitButton();
}

/**
 * Handles form submission and displays accessible feedback.
 * @param {SubmitEvent} event - Form submission event.
 * @returns {Promise<void>}
 */
async function handleFormSubmit(event) {
  event.preventDefault();
  if (!validateForm()) return;

  const endpoint = form.getAttribute('action');
  if (!endpoint || endpoint.includes('REPLACE_WITH_YOUR_FORM_ID')) {
    formStatus.textContent = getTranslation('errors.submit');
    formStatus.className = 'form-status error';
    return;
  }

  submitButton.disabled = true;
  formStatus.textContent = currentLanguage === 'de' ? 'Wird gesendet ...' : 'Sending ...';
  formStatus.className = 'form-status';

  try {
    const response = await fetch(endpoint, {
      method: 'POST',
      headers: { Accept: 'application/json' },
      body: new FormData(form)
    });

    if (!response.ok) throw new Error('Submission failed');

    form.reset();
    formStatus.textContent = getTranslation('errors.success');
    formStatus.className = 'form-status success';
  } catch (error) {
    formStatus.textContent = getTranslation('errors.submit');
    formStatus.className = 'form-status error';
  } finally {
    validateForm();
  }
}

/**
 * Initializes navigation, language controls and form validation handlers.
 * @returns {void}
 */
function initPage() {
  document.querySelectorAll('.language-button').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  });

  document.querySelector('.menu-toggle')?.addEventListener('click', toggleMobileMenu);
  document.querySelectorAll('.mobile-nav a').forEach((link) => link.addEventListener('click', closeMobileMenu));

  ['name', 'email', 'message'].forEach((id) => {
    document.getElementById(id)?.addEventListener('blur', (event) => {
      validateField(event.target);
      validatePrivacy();
      validateForm();
    });
  });

  document.getElementById('privacy')?.addEventListener('change', validateForm);
  form?.addEventListener('submit', handleFormSubmit);
  applyLanguage();
}

initPage();
