let currentLanguage = 'en';
let currentTestimonial = 0;
const form = document.getElementById('contact-form');
const submitButton = document.getElementById('submit-button');
const formStatus = document.getElementById('form-status');

/**
 * Reads a translated value from the active language and replaces testimonial placeholders when requested.
 * @param {string} key - Translation key to resolve.
 * @returns {string} Translated value or an empty string when the key is missing.
 */
function t(key) {
  return translations[currentLanguage][key] ?? '';
}

/**
 * Applies the selected language to visible text, ARIA labels and input placeholders across the page.
 * @param {'en'|'de'} language - Language code to activate.
 * @returns {void}
 */
function setLanguage(language) {
  if (!translations[language]) return;
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = tWithLanguage(language, 'title');

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translations[language][element.dataset.i18n] ?? element.textContent;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = translations[language][element.dataset.i18nHtml] ?? element.innerHTML;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', translations[language][element.dataset.i18nAria] ?? element.getAttribute('aria-label') ?? '');
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', translations[language][element.dataset.i18nPlaceholder] ?? element.getAttribute('placeholder') ?? '');
  });
  document.querySelectorAll('.language-button').forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  updateMenuLabel();
  updateTestimonialUI();
  closeMobileMenu();
}

/**
 * Resolves a translation from a language without changing the global active language.
 * @param {'en'|'de'} language - Language code to read from.
 * @param {string} key - Translation key to read.
 * @returns {string} Translated value.
 */
function tWithLanguage(language, key) {
  return translations[language]?.[key] ?? '';
}

/**
 * Updates the mobile menu button's translated accessible label.
 * @returns {void}
 */
function updateMenuLabel() {
  const toggle = document.querySelector('.menu-toggle');
  if (!toggle) return;
  const isOpen = toggle.getAttribute('aria-expanded') === 'true';
  toggle.setAttribute('aria-label', isOpen ? t('menuClose') : t('menuOpen'));
}

/**
 * Opens the mobile navigation, locks page scrolling and updates ARIA state.
 * @returns {void}
 */
function openMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const toggle = document.querySelector('.menu-toggle');
  if (!menu || !toggle) return;
  menu.classList.add('is-open');
  menu.setAttribute('aria-hidden', 'false');
  toggle.setAttribute('aria-expanded', 'true');
  updateMenuLabel();
  document.body.classList.add('menu-open');
}

/**
 * Closes the mobile navigation and restores normal page scrolling.
 * @returns {void}
 */
function closeMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const toggle = document.querySelector('.menu-toggle');
  if (!menu || !toggle) return;
  menu.classList.remove('is-open');
  menu.setAttribute('aria-hidden', 'true');
  toggle.setAttribute('aria-expanded', 'false');
  updateMenuLabel();
  document.body.classList.remove('menu-open');
}

/**
 * Toggles the mobile navigation between its open and closed states.
 * @returns {void}
 */
function toggleMobileMenu() {
  const toggle = document.querySelector('.menu-toggle');
  if (toggle?.getAttribute('aria-expanded') === 'true') closeMobileMenu();
  else openMobileMenu();
}

/**
 * Validates a single contact form field and renders its accessible error message in the active language.
 * @param {HTMLInputElement|HTMLTextAreaElement} field - Form field to validate.
 * @returns {boolean} True when the field passes its constraints.
 */
function validateField(field) {
  const error = document.getElementById(`${field.id}-error`);
  if (!error) return field.checkValidity();
  let message = '';
  if (field.id === 'name' && field.value.trim().length < 2) message = t('validationName');
  if (field.id === 'email' && !field.validity.valid) message = t('validationEmail');
  if (field.id === 'message' && field.value.trim().length < 10) message = t('validationMessage');
  field.setAttribute('aria-invalid', String(Boolean(message)));
  error.textContent = message;
  return !message;
}

/**
 * Validates the privacy checkbox and exposes its current error state in the active language.
 * @returns {boolean} True when the checkbox is checked.
 */
function validatePrivacy() {
  const checkbox = document.getElementById('privacy');
  const error = document.getElementById('privacy-error');
  if (!checkbox || !error) return false;
  const valid = checkbox.checked;
  checkbox.setAttribute('aria-invalid', String(!valid));
  error.textContent = valid ? '' : t('validationPrivacy');
  return valid;
}

/**
 * Recalculates the submit button state from all required form controls.
 * @returns {void}
 */
function updateSubmitButton() {
  if (!form || !submitButton) return;
  submitButton.disabled = !form.checkValidity() || !document.getElementById('privacy').checked;
}

/**
 * Validates the complete contact form without sending it.
 * @returns {boolean} True when every required field is valid.
 */
function validateForm() {
  const fields = ['name', 'email', 'message'];
  const fieldsValid = fields.map((id) => validateField(document.getElementById(id))).every(Boolean);
  const privacyValid = validatePrivacy();
  updateSubmitButton();
  return fieldsValid && privacyValid;
}

/**
 * Handles contact form submission and reports an accessible success or failure state.
 * @param {SubmitEvent} event - Native form submission event.
 * @returns {Promise<void>}
 */
async function handleFormSubmit(event) {
  event.preventDefault();
  if (!validateForm()) return;
  const endpoint = form.getAttribute('action');
  if (!endpoint || endpoint.includes('REPLACE_WITH_YOUR_FORM_ID')) {
    formStatus.textContent = t('endpointMissing');
    return;
  }
  submitButton.disabled = true;
  formStatus.textContent = t('sending');
  try {
    const response = await fetch(endpoint, { method: 'POST', headers: { Accept: 'application/json' }, body: new FormData(form) });
    if (!response.ok) throw new Error('Submission failed');
    form.reset();
    formStatus.textContent = t('success');
  } catch (error) {
    formStatus.textContent = t('failure');
  } finally {
    updateSubmitButton();
  }
}

/**
 * Renders the active testimonial text, author, image placeholder and navigation state.
 * @returns {void}
 */
function updateTestimonialUI() {
  const testimonial = testimonials[currentTestimonial][currentLanguage];
  const text = document.querySelector('[data-testimonial-text]');
  const author = document.querySelector('[data-testimonial-author]');
  const role = document.querySelector('[data-testimonial-role]');
  if (!text || !author || !role) return;

  text.textContent = testimonial.text;
  author.textContent = testimonial.author;
  role.textContent = testimonial.role;

  const dots = document.querySelectorAll('.testimonial-controls .dot');
  dots.forEach((dot, index) => {
    const isActive = index === currentTestimonial;
    dot.classList.toggle('is-active', isActive);
    dot.setAttribute('aria-current', isActive ? 'true' : 'false');
    dot.setAttribute('aria-label', t('testimonialNumber').replace('{number}', String(index + 1)));
  });
}

/**
 * Changes the current testimonial by a relative step and wraps around at the first and last item.
 * @param {number} step - Relative number of testimonials to move.
 * @returns {void}
 */
function changeTestimonial(step) {
  currentTestimonial = (currentTestimonial + step + testimonials.length) % testimonials.length;
  updateTestimonialUI();
}

/**
 * Selects a testimonial by its zero-based index.
 * @param {number} index - Testimonial index to activate.
 * @returns {void}
 */
function selectTestimonial(index) {
  if (index < 0 || index >= testimonials.length) return;
  currentTestimonial = index;
  updateTestimonialUI();
}

/**
 * Creates viewport-aware reveal animations for elements marked with the reveal utility classes.
 * @returns {void}
 */
function initRevealAnimations() {
  const items = document.querySelectorAll('.reveal');
  if (!('IntersectionObserver' in window)) {
    items.forEach((item) => item.classList.add('is-visible'));
    return;
  }
  const observer = new IntersectionObserver((entries, instance) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('is-visible');
      instance.unobserve(entry.target);
    });
  }, { threshold: 0.14, rootMargin: '0px 0px -5% 0px' });
  items.forEach((item) => observer.observe(item));
}

/**
 * Adds all UI listeners and initializes the interactive states of the portfolio page.
 * @returns {void}
 */
function initPage() {
  document.querySelectorAll('.language-button').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  });
  document.querySelector('.menu-toggle')?.addEventListener('click', toggleMobileMenu);
  document.querySelectorAll('.mobile-nav a').forEach((link) => link.addEventListener('click', closeMobileMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeMobileMenu();
  });
  ['name', 'email', 'message'].forEach((id) => {
    document.getElementById(id)?.addEventListener('blur', (event) => {
      validateField(event.target);
      updateSubmitButton();
    });
    document.getElementById(id)?.addEventListener('input', updateSubmitButton);
  });
  document.getElementById('privacy')?.addEventListener('change', () => {
    validatePrivacy();
    updateSubmitButton();
  });
  form?.addEventListener('submit', handleFormSubmit);

  const testimonialButtons = document.querySelectorAll('.testimonial-controls button');
  if (testimonialButtons.length >= 5) {
    testimonialButtons[0].addEventListener('click', () => changeTestimonial(-1));
    testimonialButtons[4].addEventListener('click', () => changeTestimonial(1));
  }
  document.querySelectorAll('.testimonial-controls .dot').forEach((dot) => {
    dot.addEventListener('click', () => selectTestimonial(Number(dot.dataset.testimonialIndex)));
  });

  setLanguage(currentLanguage);
  initRevealAnimations();
}

initPage();
